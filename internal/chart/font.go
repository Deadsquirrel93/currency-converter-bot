const (
	glyphWidth   = 5
	glyphHeight  = 7
	glyphAdvance = glyphWidth + 1
)

// textWidth is the width of s in font dots; unknown runes take no space.
func textWidth(s string) int {
	n := 0
	for _, r := range s {
		if _, ok := glyphs[r]; ok {
			n++
		}
	}
	if n == 0 {
		return 0
	}
	return n*glyphAdvance - 1
}
